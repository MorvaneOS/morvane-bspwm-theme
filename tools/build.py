#!/usr/bin/env python3
"""Builds the MorvaneOS bspwm theme: bspwm's example configs with the MorvaneOS look.

    python tools/build.py [path/to/bspwm/examples]

Needs only Python. The argument is bspwm's examples directory
(/usr/share/doc/bspwm/examples, the default path), with bspwmrc and sxhkdrc. Output
goes to config/; commit it, it's what the package installs.

bspwm and sxhkd read only ~/.config/bspwm/bspwmrc and ~/.config/sxhkd/sxhkdrc, so the
MorvaneOS installer copies these there for new users.
"""

import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BASE = Path(sys.argv[1]) if len(sys.argv) > 1 else Path('/usr/share/doc/bspwm/examples')

# Keep in step with the window colours in morvane-gtk-theme
PASTEL = '#F4A6C6'
NIGHT = '#120C16'
PAPER = '#F5EEF3'
SURFACE = '#1A1220'
SELECTED = '#4A3552'
BORDER = '#2A1C32'
WALLPAPER = '/usr/share/backgrounds/morvaneos/twilight.png'

BSPWMRC_THEME = f'''
# ---- MorvaneOS look, added by morvane-bspwm-theme ----
# The focused window has a Pastel Pink border
bspc config normal_border_color   "{BORDER}"
bspc config active_border_color   "{SELECTED}"
bspc config focused_border_color  "{PASTEL}"
bspc config presel_feedback_color "{PASTEL}"

xwallpaper --zoom {WALLPAPER} &
'''

# dmenu takes its colours on the command line
DMENU = f"dmenu_run -nb '{SURFACE}' -nf '{PAPER}' -sb '{PASTEL}' -sf '{NIGHT}'"


def build() -> None:
	bspwmrc, sxhkdrc = BASE / 'bspwmrc', BASE / 'sxhkdrc'
	if not (bspwmrc.is_file() and sxhkdrc.is_file()):
		sys.exit(f"bspwm's examples not found in {BASE} (pass the path to /usr/share/doc/bspwm/examples)")
	sxhkd = sxhkdrc.read_text()
	if sxhkd.count('\tdmenu_run\n') != 1:
		sys.exit("bspwm's example sxhkdrc no longer runs dmenu_run the same way; update tools/build.py")

	out = ROOT / 'config'
	shutil.rmtree(out, ignore_errors=True)
	out.mkdir()
	(out / 'bspwmrc').write_text(bspwmrc.read_text().rstrip('\n') + '\n' + BSPWMRC_THEME)
	(out / 'bspwmrc').chmod(0o755)
	(out / 'sxhkdrc').write_text(
		'# bspwm example sxhkdrc with the MorvaneOS look: generated by tools/build.py in morvane-bspwm-theme.\n\n'
		+ sxhkd.replace('\tdmenu_run\n', f'\t{DMENU}\n')
	)
	print('Built the bspwm configs.')


if __name__ == '__main__':
	build()
